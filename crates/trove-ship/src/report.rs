//! The redaction report: what was removed, why, and where. It never contains a
//! removed value, only its placeholder, category, detector and length.

use std::collections::BTreeMap;

use serde::Serialize;

use crate::redact::{AllowedItem, OverriddenAllow, Redactor, ReportItem};

#[derive(Debug, Clone, Serialize)]
pub struct Report {
    pub tool: String,
    pub project: String,
    pub format: String,
    pub agent_review: String,
    pub agent_findings: usize,
    pub totals: BTreeMap<String, usize>,
    pub high_confidence: usize,
    pub items: Vec<ReportItem>,
    pub allowed: Vec<AllowedItem>,
    pub overridden_allowlist: Vec<OverriddenAllow>,
    pub files_excluded: usize,
    pub verification: String,
}

impl Report {
    pub fn new(
        redactor: &Redactor,
        project: &str,
        format: &str,
        agent_review: String,
        agent_findings: usize,
        files_excluded: usize,
    ) -> Self {
        let mut items = redactor.items();
        for item in &mut items {
            item.reason = redactor.sanitize_label(&item.reason);
        }
        let mut totals = BTreeMap::new();
        for item in &items {
            *totals.entry(item.category.label().to_string()).or_insert(0) += 1;
        }
        Self {
            tool: format!("trove-ship {}", env!("CARGO_PKG_VERSION")),
            project: redactor.sanitize_label(project),
            format: format.to_string(),
            agent_review,
            agent_findings,
            high_confidence: items
                .iter()
                .filter(|i| i.confidence == crate::redact::Confidence::High)
                .count(),
            totals,
            items,
            allowed: redactor.allowed(),
            overridden_allowlist: redactor.overridden().to_vec(),
            files_excluded,
            verification: "pending".into(),
        }
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).unwrap_or_else(|_| "{}".into()) + "\n"
    }

    pub fn to_markdown(&self) -> String {
        let mut out = format!("# Redaction report: {}\n\n", self.project);
        out.push_str(&format!(
            "Generated by {}. Every value below was removed before the docs were written. \
             The values themselves are not in this report: each row gives the placeholder \
             that replaced it, what kind of information it was, which detector found it, \
             and where it appeared.\n\n",
            self.tool
        ));
        out.push_str("## Summary\n\n");
        out.push_str(&format!(
            "- **Distinct values removed**: {}\n",
            self.items.len()
        ));
        out.push_str(&format!(
            "- **High confidence**: {}\n",
            self.high_confidence
        ));
        for (cat, n) in &self.totals {
            out.push_str(&format!("- **{cat}**: {n}\n"));
        }
        out.push_str(&format!("- **Agent review**: {}", self.agent_review));
        if self.agent_review != "not run" {
            out.push_str(&format!(" ({} extra findings)", self.agent_findings));
        }
        out.push('\n');
        out.push_str(&format!(
            "- **Files excluded by .troveignore**: {}\n",
            self.files_excluded
        ));
        out.push_str(&format!("- **Verification**: {}\n\n", self.verification));

        out.push_str("## Removed\n\n");
        if self.items.is_empty() {
            out.push_str("_Nothing needed redacting._\n\n");
        } else {
            out.push_str(
                "| Placeholder | Category | Confidence | Detector | Why | Length | Where |\n",
            );
            out.push_str("|---|---|---|---|---|---|---|\n");
            for i in &self.items {
                let mut wheres: Vec<String> = i
                    .locations
                    .iter()
                    .take(6)
                    .map(|l| format!("{}:{}", l.origin, l.line))
                    .collect();
                if i.locations.len() > 6 {
                    wheres.push(format!("and {} more", i.locations.len() - 6));
                }
                out.push_str(&format!(
                    "| `{}` | {} | {:?} | `{}` | {} | {} | {} |\n",
                    i.placeholder,
                    i.category.label(),
                    i.confidence,
                    i.detector,
                    i.reason.replace('|', "\\|"),
                    i.length,
                    wheres.join(", ")
                ));
            }
            out.push('\n');
        }

        if !self.allowed.is_empty() {
            out.push_str("## Kept by .troveignore\n\n");
            out.push_str("| Rule | Category | Detector | Matches |\n|---|---|---|---|\n");
            for a in &self.allowed {
                out.push_str(&format!(
                    "| `{}` | {} | `{}` | {} |\n",
                    a.rule,
                    a.category.label(),
                    a.detector,
                    a.occurrences
                ));
            }
            out.push('\n');
        }

        if !self.overridden_allowlist.is_empty() {
            out.push_str("## Allowlist entries ignored\n\n");
            out.push_str(
                "These rules tried to keep a high-confidence secret. Secrets cannot be \
                 allowlisted, so they were redacted anyway. Remove the rules.\n\n",
            );
            for o in &self.overridden_allowlist {
                out.push_str(&format!("- `{}` (matched by `{}`)\n", o.rule, o.detector));
            }
            out.push('\n');
        }
        out
    }
}
