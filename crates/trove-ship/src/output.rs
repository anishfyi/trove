/// Write files into `out`. A non-empty directory not written by trove-ship is
/// refused unless `force` is set. On a re-run, files listed in the marker from
/// the previous run are removed first; nothing else in the directory is touched.
pub fn write(out: &Path, files: &Files, force: bool) -> Result<Vec<PathBuf>> {
    if out.exists() {
        if !out.is_dir() {
            bail!("{} exists and is not a directory", out.display());
        }
        let marker = out.join(MARKER);
        let empty = fs::read_dir(out)?.next().is_none();
        if !marker.exists() && !empty && !force {
            bail!(
                "{} is not empty and was not written by trove-ship; pass --force or pick another --out",
                out.display()
            );
        }
        if let Ok(previous) = fs::read_to_string(&marker) {
            for rel in previous.lines().skip(1).filter(|l| is_safe_rel(l)) {
                let _ = fs::remove_file(out.join(rel));
            }
        }
    }
    fs::create_dir_all(out).with_context(|| format!("create {}", out.display()))?;
    let mut written = Vec::new();
    let mut manifest = String::from("# Written by trove-ship. Lists the files it owns here.\n");
    for (rel, content) in files {
        if !is_safe_rel(rel) {
            bail!("refusing to write outside the output directory: {rel}");
        }
        let path = out.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&path, content).with_context(|| format!("write {}", path.display()))?;
        manifest.push_str(rel);
        manifest.push('\n');
        written.push(path);
    }
    fs::write(out.join(MARKER), manifest)?;
    Ok(written)
}

fn is_safe_rel(rel: &str) -> bool {
    !rel.is_empty()
        && !rel.starts_with('/')
        && !rel.starts_with('\\')
        && !rel.contains(':')
        && rel.split(['/', '\\']).all(|p| p != "..")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("trove-ship-out-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        d
    }

    #[test]
    fn refuses_foreign_dir_and_only_replaces_own_files() {
        let d = tmp("foreign");
        fs::create_dir_all(&d).unwrap();
        fs::write(d.join("keep.txt"), "mine").unwrap();
        let both = vec![
            ("a.md".to_string(), "x".to_string()),
            ("b.md".to_string(), "y".to_string()),
        ];
        assert!(write(&d, &both, false).is_err());
        write(&d, &both, true).unwrap();
        let one = vec![("a.md".to_string(), "z".to_string())];
        write(&d, &one, false).unwrap();
        assert!(d.join("keep.txt").exists());
        assert!(!d.join("b.md").exists());
        assert_eq!(fs::read_to_string(d.join("a.md")).unwrap(), "z");
        let _ = fs::remove_dir_all(&d);
    }

    #[test]
    fn rejects_unsafe_paths() {
        assert!(!is_safe_rel("../x"));
        assert!(!is_safe_rel("/etc/x"));
        assert!(!is_safe_rel("a/../../x"));
        assert!(is_safe_rel("docs/a.md"));
    }
}
