//! Turn redacted documents into output files: a Markdown folder, a single
//! Markdown file, or a static HTML site. Rendering is pure; writing happens
//! only after the fail-closed verification passed.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde::Serialize;

use crate::docs::{include, Doc};
use crate::render::{escape, markdown_to_html};
use crate::report::Report;

/// Marks a directory as written by trove-ship so a re-run may replace it.
pub const MARKER: &str = ".trove-ship";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, clap::ValueEnum)]
#[serde(rename_all = "lowercase")]
pub enum Format {
    /// One Markdown file per section plus an index
    Folder,
    /// Everything in one HANDOFF.md
    Single,
    /// Static HTML site
    Site,
}

impl Format {
    pub fn label(self) -> &'static str {
        match self {
            Self::Folder => "folder",
            Self::Single => "single",
            Self::Site => "site",
        }
    }
}

/// Files to write, as (relative path, contents).
pub type Files = Vec<(String, String)>;

pub fn render(format: Format, project: &str, docs: &[Doc], report: &Report) -> Files {
    let mut files = match format {
        Format::Folder => folder(project, docs),
        Format::Single => single(project, docs),
        Format::Site => site(project, docs, report),
    };
    if format != Format::Site {
        files.push(("REDACTION_REPORT.md".into(), report.to_markdown()));
    }
    files.push(("redaction-report.json".into(), report.to_json()));
    files
}

fn folder(project: &str, docs: &[Doc]) -> Files {
    let mut index = format!(
        "# {project}: developer handoff\n\n\
         Generated by trove-ship from the project, its Trove index and its project trove. \
         Private information was removed first; see [the redaction report](REDACTION_REPORT.md).\n\n"
    );
    for d in docs {
        index.push_str(&format!("- [{}]({}): {}\n", d.title, d.file, d.summary));
    }
    let mut files = vec![("README.md".to_string(), index)];
    for d in docs {
        files.push((d.file.to_string(), d.body.clone()));
    }
    files
}

fn single(project: &str, docs: &[Doc]) -> Files {
    let mut out = format!(
        "# {project}: developer handoff\n\n\
         Generated by trove-ship. Private information was removed first; see \
         `REDACTION_REPORT.md` next to this file.\n\n## Contents\n\n"
    );
    for d in docs {
        out.push_str(&format!(
            "- [{}](#{}): {}\n",
            d.title,
            crate::render::slug(d.title),
            d.summary
        ));
    }
    out.push('\n');
    for d in docs {
        // Replace each doc's own H1 with a section heading and nest the rest.
        let body = d.body.split_once('\n').map(|(_, rest)| rest).unwrap_or("");
        out.push_str(&format!("## {}\n\n", d.title));
        out.push_str(&include(body, 3));
        out.push_str("\n\n");
    }
    vec![("HANDOFF.md".to_string(), out)]
}

fn site(project: &str, docs: &[Doc], report: &Report) -> Files {
    let mut pages: Vec<(String, String, String)> = vec![("index.html".into(), "Home".into(), {
        let mut md = format!(
                "# {project}: developer handoff\n\nGenerated by trove-ship. Private information was removed first; see [the redaction report](redaction-report.html).\n\n"
            );
        for d in docs {
            md.push_str(&format!("- [{}]({}): {}\n", d.title, d.file, d.summary));
        }
        md
    })];
    for d in docs {
        pages.push((
            d.file.replace(".md", ".html"),
            d.title.to_string(),
            d.body.clone(),
        ));
    }
    pages.push((
        "redaction-report.html".into(),
        "Redaction report".into(),
        report.to_markdown(),
    ));

    let nav: String = pages
        .iter()
        .map(|(file, title, _)| format!("<a href=\"{}\">{}</a>", escape(file), escape(title)))
        .collect::<Vec<_>>()
        .join("\n");
    pages
        .iter()
        .map(|(file, title, md)| {
            (
                file.clone(),
                page(project, title, &nav, &markdown_to_html(md)),
            )
        })
        .collect()
}

